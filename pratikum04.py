df.duplicated().sum()

# Cek missing value
df.isnull().sum()

df['Stunting'].unique()

df['Jenis Kelamin'].unique()

# 1. Mapping kolom Stunting -> biner
map_stunt = {'Stunted': 1, 'Severely Stunted': 1, 'Normal': 0, 'Tall': 0}
df['Stunting_bin'] = df['Stunting'].map(map_stunt).astype('Int64')

