# Import Library
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import LabelEncoder
from sklearn.naive_bayes import CategoricalNB
from sklearn.metrics import (accuracy_score, confusion_matrix, classification_report, ConfusionMatrixDisplay)

"""# Menghitung Probabilitas Kasus Cacat Kunci Pas"""

# Informasi produksi
produksi_M1 = 30
produksi_M2 = 20
total_produksi = produksi_M1 + produksi_M2

# Probabilitas
P_C = 0.01
P_M2_diberikan_C = 0.5
P_M2 = produksi_M2 / total_produksi

# Teorema Bayes
P_C_diberikan_M2 = (
    P_M2_diberikan_C * P_C
) / P_M2

print("P(M2) =", P_M2)
print("P(C) =", P_C)
print("P(M2|C) =", P_M2_diberikan_C)
print("P(C|M2) =", P_C_diberikan_M2)
print("Persentase cacat Mesin 2 =", P_C_diberikan_M2 * 100, "%")

"""# Membuat Dataset dan DataFrame"""

data = {
    'C1': [
        'Murah', 'Sedang', 'Mahal', 'Mahal', 'Mahal',
        'Sedang', 'Murah', 'Murah', 'Mahal', 'Sedang'
    ],

    'C2': [
        'Dekat', 'Dekat', 'Dekat', 'Jauh', 'Sedang',
        'Jauh', 'Jauh', 'Sedang', 'Jauh', 'Sedang'
    ],

    'C3': [
        'Tidak', 'Tidak', 'Tidak', 'Tidak', 'Tidak',
        'Ada', 'Ada', 'Tidak', 'Ada', 'Ada'
    ],

    'C4': [
        'Ya', 'Ya', 'Ya', 'Tidak', 'Tidak',
        'Tidak', 'Tidak', 'Ya', 'Tidak', 'Ya'
    ]
}

df = pd.DataFrame(data)

print("Dataset Perumahan:")
display(df)

"""# Melihat Informasi Dataset

"""

print("Informasi Dataset:")
df.info()

print("\nJumlah Data:")
print(df.shape)

print("\nJumlah Missing Value:")
print(df.isnull().sum())

print("\nJumlah Data Setiap Kelas:")
print(df['C4'].value_counts())

"""# Menghitung Probabilitas Prior"""

jumlah_data = len(df)
prior = df['C4'].value_counts() / jumlah_data

print("Probabilitas Prior:")
print(prior)

"""# Menghitung Frekuensi dan Likelihood Manual"""

fitur = ['C1', 'C2', 'C3']
for kolom in fitur:
    print(f"\nFrekuensi {kolom}:")
    frekuensi = pd.crosstab(df[kolom], df['C4'])
    display(frekuensi)

    print(f"\nLikelihood {kolom}:")
    likelihood = pd.crosstab(df[kolom], df['C4'], normalize='columns')
    display(likelihood)

"""# Menghitung Probabilitas Manual dan Normalisasi"""

data_baru = {
    'C1': 'Mahal',
    'C2': 'Sedang',
    'C3': 'Ada'
}

kelas = ['Ya', 'Tidak']
hasil = {}

for kelas_target in kelas:
    probabilitas = prior[kelas_target]
    for kolom, kategori in data_baru.items():
        jumlah_kategori = (
            (df[kolom] == kategori) &
            (df['C4'] == kelas_target)
        ).sum()
        jumlah_kelas = (
            df['C4'] == kelas_target
        ).sum()
        likelihood = jumlah_kategori / jumlah_kelas
        probabilitas *= likelihood
    hasil[kelas_target] = probabilitas

print("Probabilitas Sebelum Normalisasi:")
for nama, nilai in hasil.items():
    print(nama, "=", nilai)
total = sum(hasil.values())
print("\nProbabilitas Setelah Normalisasi:")
for nama, nilai in hasil.items():
    print(nama, "=", nilai / total)
prediksi_manual = max(hasil, key=hasil.get)

print("\nHasil Prediksi Manual:")
print(prediksi_manual)

"""# Melakukan Encoding Data Kategorikal"""

df_encoded = df.copy()
encoders = {}
for kolom in df.columns:
    le = LabelEncoder()
    df_encoded[kolom] = le.fit_transform(df[kolom])
    encoders[kolom] = le

print("Dataset Setelah Encoding:")
display(df_encoded)

print("\nMapping Encoding:")
for kolom, le in encoders.items():
    mapping = dict(zip(le.classes_, le.transform(le.classes_) ) )
    print(kolom, ":", mapping)

"""# Menentukan Fitur dan Target"""

X = df_encoded[['C1', 'C2', 'C3']]
y = df_encoded['C4']

print("Fitur X:")
display(X)
print("\nTarget y:")
print(y)

"""# Membangun Model Categorical Naïve Bayes"""

model = CategoricalNB(alpha=1.0)
model.fit(X, y)

print("Model CategoricalNB berhasil dilatih.")

"""# Melakukan Prediksi Data Baru"""

data_baru_df = pd.DataFrame([{
    'C1': encoders['C1'].transform(['Mahal'])[0],
    'C2': encoders['C2'].transform(['Sedang'])[0],
    'C3': encoders['C3'].transform(['Ada'])[0]
}])

print("Data Baru:")
display(data_baru_df)
prediksi = model.predict(data_baru_df)
probabilitas = model.predict_proba(data_baru_df)
kelas_prediksi = encoders['C4'].inverse_transform(prediksi)

print("Hasil Prediksi:")
print(kelas_prediksi[0])
print("\nProbabilitas Prediksi:")
for nama_kelas, nilai in zip(
    encoders['C4'].classes_,
    probabilitas[0]
):
    print(nama_kelas, "=", nilai)

"""# Visualisasi Probabilitas Prediksi"""

kelas = encoders['C4'].classes_
plt.figure(figsize=(7, 5))
plt.bar(kelas, probabilitas[0])
plt.title('Probabilitas Prediksi Categorical Naive Bayes')
plt.xlabel('Kelas')
plt.ylabel('Probabilitas')
plt.ylim(0, 1)
plt.grid( axis='y', linestyle='--', alpha=0.5)
plt.show()

"""# Evaluasi Model"""

y_pred = model.predict(X)
akurasi = accuracy_score(y, y_pred)
print("Accuracy Score:")
print(akurasi)
print("\nClassification Report:")
print(classification_report( y, y_pred, target_names=encoders['C4'].classes_, zero_division=0))

"""# Confusion Matrix"""

cm = confusion_matrix(y, y_pred)
print("Confusion Matrix:")
print(cm)
disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=encoders['C4'].classes_)
disp.plot(cmap='Blues')
plt.title('Confusion Matrix Categorical Naive Bayes')
plt.show()

"""# Menguji Pengaruh Alpha (Laplace Smoothing)"""

nilai_alpha = [0.1, 0.5, 1.0, 2.0]
for alpha in nilai_alpha:
    model_alpha = CategoricalNB(alpha=alpha)
    model_alpha.fit(X, y)
    prediksi_alpha = model_alpha.predict(data_baru_df)
    probabilitas_alpha = model_alpha.predict_proba(data_baru_df)
    hasil_prediksi = encoders['C4'].inverse_transform(prediksi_alpha)

    print("\nAlpha:", alpha)
    print("Prediksi:", hasil_prediksi[0])
    print("Probabilitas:", probabilitas_alpha[0])

